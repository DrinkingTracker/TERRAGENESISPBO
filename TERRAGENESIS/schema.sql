-- 3. VIEW (untuk grid lahan, dashboard admin, riwayat penanaman)
-- ------------------------------------------------------------

-- Status tiap petak untuk grid 10x10 dan Kelola Lahan:
-- 'nonaktif' (dimatikan admin), 'terisi' (ada donasi aktif), atau 'kosong'.
CREATE VIEW v_status_petak AS
SELECT p.id,
       p.wilayah_id,
       w.nama AS wilayah,
       p.nomor,
       p.status AS status_lahan,
       CASE
           WHEN p.status = 'nonaktif' THEN 'nonaktif'
           WHEN EXISTS (SELECT 1 FROM donasi d
                        WHERE d.petak_id = p.id AND d.status <> 'ditolak') THEN 'terisi'
           ELSE 'kosong'
       END AS status_petak
FROM petak p
JOIN wilayah w ON w.id = p.wilayah_id;

-- Kartu Dashboard Admin. Definisi tiap angka masih ASUMSI dari label Figma
-- (belum dikonfirmasi pengguna satu per satu):
--  total_pohon_ditanam = pohon pada donasi berstatus ditanam/selesai
--  lahan_tersedia      = petak aktif tanpa donasi aktif
--  total_donasi        = jumlah rupiah donasi yang sudah disetujui atau lebih
--  total_pengguna      = jumlah akun donatur
-- Catatan: contoh angka di Dashboard (78 ditanam + 464 tersedia = 542, bukan 500)
-- dan di halaman Lahan (37/100 petak terisi) adalah data CONTOH Figma yang
-- berbeda-beda, bukan indikasi bug di query ini.
CREATE VIEW v_dashboard AS
SELECT
    (SELECT COALESCE(SUM(jumlah_pohon), 0) FROM donasi
      WHERE status IN ('ditanam', 'selesai'))                       AS total_pohon_ditanam,
    (SELECT COUNT(*) FROM v_status_petak WHERE status_petak = 'kosong') AS lahan_tersedia,
    (SELECT COALESCE(SUM(pb.jumlah), 0)
       FROM pembayaran pb JOIN donasi d ON d.id = pb.donasi_id
      WHERE d.status IN ('disetujui', 'ditanam', 'selesai'))        AS total_donasi,
    (SELECT COUNT(*) FROM pengguna WHERE peran = 'donatur')         AS total_pengguna;

-- Riwayat Penanaman: satu baris per tanggal + wilayah, petaknya digabung.
-- Tetap konsisten dengan "1 donasi = 1 petak" karena penggabungan hanya di tampilan.
CREATE VIEW v_riwayat_penanaman AS
SELECT d.ditanam_pada::date              AS tanggal,
       w.nama                            AS wilayah,
       string_agg('#' || p.nomor::text, ', ' ORDER BY p.nomor) AS lahan,
       SUM(d.jumlah_pohon)               AS jumlah_pohon
FROM donasi d
JOIN petak p   ON p.id = d.petak_id
JOIN wilayah w ON w.id = p.wilayah_id
WHERE d.status IN ('ditanam', 'selesai')
  AND d.ditanam_pada IS NOT NULL
GROUP BY d.ditanam_pada::date, w.nama;

