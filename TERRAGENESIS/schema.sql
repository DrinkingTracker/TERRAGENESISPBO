-- ------------------------------------------------------------
-- 1. TABEL
-- ------------------------------------------------------------

CREATE TABLE pengguna (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    peran         VARCHAR(10)  NOT NULL DEFAULT 'donatur'
                  CHECK (peran IN ('donatur', 'admin')),
    dibuat_pada   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE wilayah (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100) NOT NULL UNIQUE
);

-- Petak: 100 per wilayah (grid 10x10).
-- status = status lahan yang diatur admin (Kelola Lahan: "Aktif").
-- Terisi/kosong TIDAK disimpan di sini; dihitung dari donasi aktif (lihat v_status_petak).
CREATE TABLE petak (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wilayah_id INTEGER     NOT NULL REFERENCES wilayah(id) ON DELETE RESTRICT,
    nomor      INTEGER     NOT NULL CHECK (nomor BETWEEN 1 AND 100),
    status     VARCHAR(10) NOT NULL DEFAULT 'aktif'
               CHECK (status IN ('aktif', 'nonaktif')),
    UNIQUE (wilayah_id, nomor)
);

-- Katalog harga per pohon (Rp 15.000).
CREATE TABLE pohon (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    harga INTEGER NOT NULL CHECK (harga > 0)
);

CREATE TABLE metode_pembayaran (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metode VARCHAR(50) NOT NULL UNIQUE
);

-- Satu donasi = satu petak, boleh banyak pohon.
-- Alur status: menunggu -> disetujui -> ditanam -> selesai, atau menunggu -> ditolak.
-- "disetujui" sudah DIKONFIRMASI sebagai istilah final (Kelola Donasi & Donasi Saya
-- di UI harus konsisten memakai "Disetujui").
-- nama_donatur dan pesan diisi dari form halaman Donasi ("Nama Donatur",
-- "Pesan / Harapan Donatur"); jumlah_pohon dari counter +/- di halaman yang sama.
CREATE TABLE donasi (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id    INTEGER      NOT NULL REFERENCES pengguna(id) ON DELETE RESTRICT,
    petak_id       INTEGER      NOT NULL REFERENCES petak(id)    ON DELETE RESTRICT,
    pohon_id       INTEGER      NOT NULL REFERENCES pohon(id)    ON DELETE RESTRICT,
    nama_donatur   VARCHAR(100) NOT NULL,
    pesan          VARCHAR(500),
    jumlah_pohon   INTEGER      NOT NULL CHECK (jumlah_pohon > 0),
    status         VARCHAR(10)  NOT NULL DEFAULT 'menunggu'
                   CHECK (status IN ('menunggu', 'disetujui', 'ditanam', 'selesai', 'ditolak')),
    dibuat_pada    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    disetujui_pada TIMESTAMP,
    ditanam_pada   TIMESTAMP,
    selesai_pada   TIMESTAMP
);

-- Satu petak hanya boleh punya satu donasi aktif (donasi 'ditolak' membebaskan petak).
CREATE UNIQUE INDEX uq_donasi_petak_aktif
    ON donasi (petak_id)
    WHERE status <> 'ditolak';

CREATE INDEX ix_donasi_pengguna ON donasi (pengguna_id);
CREATE INDEX ix_donasi_status   ON donasi (status);

-- Satu donasi paling banyak satu pembayaran.
-- Validasi file bukti_bayar_path (JPG/PNG, maksimal 5MB) dilakukan di
-- aplikasi (DonasiService), sesuai batas yang ditampilkan di halaman Donasi
-- ("Upload bukti transfer, JPG/PNG, maksimal 5MB"); TIDAK ditegakkan oleh database.
CREATE TABLE pembayaran (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donasi_id            INTEGER      NOT NULL UNIQUE REFERENCES donasi(id) ON DELETE CASCADE,
    metode_pembayaran_id INTEGER      NOT NULL REFERENCES metode_pembayaran(id) ON DELETE RESTRICT,
    jumlah               INTEGER      NOT NULL CHECK (jumlah >= 0),
    bukti_bayar_path     VARCHAR(255),
    dibayar_pada         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dokumentasi (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donasi_id     INTEGER      NOT NULL REFERENCES donasi(id)   ON DELETE CASCADE,
    diunggah_oleh INTEGER      NOT NULL REFERENCES pengguna(id) ON DELETE RESTRICT,
    path_foto     VARCHAR(255) NOT NULL,
    diunggah_pada TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_dokumentasi_donasi ON dokumentasi (donasi_id);

